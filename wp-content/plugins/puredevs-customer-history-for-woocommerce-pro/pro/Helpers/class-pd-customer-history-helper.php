		/**
		 * Formats the URL's
		 *
		 * @param $session_url
		 *
		 * @return array
		 */
		public static function pdwchs_session_url( $session_url) {
			$tr_class = "";
			$is_session_action = false;

			if ( strpos( $session_url, 'CTION::' ) == 1 ) {
				$is_session_action = true;
				$url_array = explode( '::', $session_url );
				$tr_class = 'action action-' . $url_array['1'];

				switch ( $url_array['1'] ) {
					case 'search':
						$url = esc_html__( 'Search', 'puredevs-customer-history-for-woocommerce' ) . ': ' . $url_array['2'];
						$icon = 'search';
						break;

					case 'add_to_cart':
						$url = esc_html__( 'Add to cart', 'puredevs-customer-history-for-woocommerce' ) . ': x' . $url_array['3'] . ' products #' . $url_array['2'];
						$icon = 'cart';
						break;

					case 'new_order':
						$url = esc_html__( 'New order', 'puredevs-customer-history-for-woocommerce' ) . ': #' . $url_array['2'];
						$icon = 'yes-alt';
						break;

					default:
						$url = 'default_action';
						break;
				}

			} elseif ( strpos( $session_url, 'OT::' ) == 1 ) {

				if ( get_option( 'pd-woo-show_bot_sessions' ) ) {
					$is_session_action = true;
					$url_array = explode( '::', $session_url );
					$url = '<a href="'.get_site_url() . '/' . $url_array[2].'" target="_blank">' . get_site_url() . '/' . $url_array[2] . '</a><br /><span class="dashicons dashicons-sos mr-5"></span>' . $url_array[1];
					$tr_class = 'bot';
					$icon = 'media-default';
				} else {
				    $url = '';
				}

			} else {
			    $url = get_site_url() . '/' . $session_url;
			}

			if ( ! empty( $url ) ) {

				if ( $is_session_action ) {
					$session_url = '<strong class="' . $tr_class . '"><span class="dashicons dashicons-' . $icon . '" style="margin-right: 5px;"></span> ' . $url . '</strong>';
					$action_url  = '<a href="" onclick="return false;" class="button disabled"><span class="dashicons dashicons-visibility vertical-align-middle"></span></a>';
				} else {
					$session_url = '<span class="dashicons dashicons-media-default mr-5"></span><a href="' . $url . '" title="' . $url . '" target="_blank" class="">' . $url . '</a>';
					$action_url  = '<a href="' . $url . '" title="' . $url . '" target="_blank" class="button"><span class="dashicons dashicons-visibility vertical-align-middle"></span></a>';
				}

			} else {
				$session_url = '';
				$action_url = '';
			}

			return array(
				'session_url' => $session_url,
				'action_url' => $action_url
			);

		}

		/**
		 * Filters and returns only the product view data from the provided dataset.
		 *
		 * Iterates through the given array of data objects and selects those whose 'url'
		 * property starts with 'product/'. The filtered data is returned as an array.
		 *
		 * @param array $datas Array of data objects, each expected to have a 'url' property.
		 * @return array Array of data objects where 'url' starts with 'product/'.
		 */
		public static function pdwchs_get_view_products( $datas ){
			$products_only = array();
			if(!empty($datas)){
				foreach($datas as $data){
					if(strcmp(substr($data->url, 0, 8),"product/")==0){
						$products_only[] = $data;
					}
				}
			}
			return $products_only;
        }
