// Writes ../screenshots/INDEX.md from shots.json + the files actually present.  node build-index.mjs
import fs from 'node:fs';
import path from 'node:path';
const here = path.dirname(new URL(import.meta.url).pathname);
const shots = JSON.parse(fs.readFileSync(path.join(here, 'shots.json'), 'utf8'));
const dir = path.join(here, '..', 'screenshots');
const rows = shots.map(s => {
  const f = path.join(dir, `${s.id}.png`);
  const ok = fs.existsSync(f);
  const kb = ok ? Math.round(fs.statSync(f).size / 1024) : 0;
  const url = s.url.replace('/wp-admin/admin.php?page=', '').replace('/wp-admin/', '');
  return `| ${s.id} | ${s.tier || 'pro'} | ${s.title || ''} | \`${url}\` | ${(s.callouts || []).map(c => `${c.n} ${c.label}`).join(' · ')} | ${ok ? kb + ' KB' : 'MISSING'} |`;
});
const missing = shots.filter(s => !fs.existsSync(path.join(dir, `${s.id}.png`))).map(s => s.id);
fs.writeFileSync(path.join(dir, 'INDEX.md'), `# Screenshot index\n\nGenerated by \`tooling/build-index.mjs\` on ${new Date().toISOString().slice(0, 10)}. ${shots.length} shots defined, ${shots.length - missing.length} present.${missing.length ? ' Missing: ' + missing.join(', ') : ''}\n\n| ID | Tier | Screen | Page | Callouts | File |\n|---|---|---|---|---|---|\n${rows.join('\n')}\n`);
console.log(`${shots.length} defined, ${missing.length} missing${missing.length ? ': ' + missing.join(', ') : ''}`);
